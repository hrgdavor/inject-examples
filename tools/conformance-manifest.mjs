/**
 * The conformance manifest: a machine-readable map of the test suite, written
 * for someone porting the matcher to a new language.
 *
 * It answers the three questions a new implementation asks first — *what must I
 * read, what is in it, and what does each field mean* — without their having to
 * reverse-engineer a generator. The counts are **derived** from the corpora, so
 * the manifest cannot drift from what the suite actually asserts; only the prose
 * is authored here.
 *
 *   node tools/conformance-manifest.mjs           # write test/vectors/manifest.json
 *   node tools/conformance-manifest.mjs --check    # exit 1 when it is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
