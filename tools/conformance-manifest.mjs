const body = JSON.stringify(manifest, null, 2);
const out = `${body}\n`;

if (process.argv.includes('--check')) {
    let have = null;
    try { have = readFileSync(OUT, 'utf8'); } catch { /* absent */ }
    if (have === out) {
        console.log(`conformance manifest: ok (${section.length} section rows, ${manifest.corpora[1].rows} lexical rows, ${manifest.corpora[2].rows} profile rows)`);
        process.exit(0);
    }
    if (have === null) {
        console.error(`conformance manifest: ${OUT} is missing — run: node tools/conformance-manifest.mjs`);
    } else {
        const want = out.split('\n');
        const got = have.split('\n');
        const at = want.findIndex((line, index) => line !== got[index]);
        console.error(`conformance manifest: ${OUT} is stale — run: node tools/conformance-manifest.mjs`);
        console.error(`    first difference at line ${at + 1}`);
        console.error(`    committed: ${JSON.stringify(got[at] ?? '')}`);
        console.error(`    expected:  ${JSON.stringify(want[at] ?? '')}`);
    }
    process.exit(1);
}

