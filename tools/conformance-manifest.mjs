/**
 * The conformance manifest: a machine-readable map of the test suite, written
 * for someone porting the matcher to a new language.
 *
 * It answers the three questions a new implementation asks first — *what must I
 * read, what is in it, and what does each field mean* — without their having to
 * reverse-engineer a generator. The counts are **derived** from the corpora, so
 * the manifest cannot drift from what the suite actually asserts; only the prose
 * is authored here.
 *
 *   node tools/conformance-manifest.mjs           # write test/vectors/manifest.json
 *   node tools/conformance-manifest.mjs --check    # exit 1 when it is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SECTION = 'test/vectors/section-vectors.json';
const LEXICAL = 'test/vectors/lexical-vectors.json';
const OUT = 'test/vectors/manifest.json';

const read = (path) => JSON.parse(readFileSync(path, 'utf8'));

/** How many rows carry each value of a field, for the fields worth counting. */
function tally(rows, field) {
    const counts = new Map();
    for (const row of rows) {
        const key = row[field] === null || row[field] === undefined ? 'null' : String(row[field]);
        counts.set(key, (counts.get(key) ?? 0) + 1);
    }
    return Object.fromEntries([...counts].sort((l, r) => (l[0] < r[0] ? -1 : 1)));
}

const section = read(SECTION);
const lexical = read(LEXICAL);

// A resolution row names a fixture and expects text; a parse row names only a
// reference, so it carries no input. The generated corpus marks this by `input`
// being null rather than by a `mode` field, because `mode` is a *case*
// declaration in the generator, not part of the row that is written out.
const parseRows = section.filter((row) => row.input === null);
const resolveRows = section.filter((row) => row.input !== null);
const errorRows = section.filter((row) => row.error !== null);
const warnRows = section.filter((row) => row.warning !== null);

const manifest = {
    $comment: [
        'Generated by tools/conformance-manifest.mjs — do not hand-edit.',
        'The row counts are read from the corpora, so this file cannot drift from them.',
        'Regenerate with `node tools/conformance-manifest.mjs`; `--check` fails when it is stale.',
    ],
    suite: 'section-mapping',
    spec: '0.1-draft',
    rfc: 'doc/rfc/section-mapping.md',
    normative: 'doc/section-matching.md',
    reference: 'lib/section.mjs',
    // The order a port should implement in: cheapest layer first, each one
    // independent of the layers below it.
    layers: [
        {
            layer: 1,
            name: 'grammar',
            file: SECTION,
            rows: parseRows.length,
            selector: 'rows with input === null (they consult no file)',
            asserts: ['canonical spelling', 'thrown error message'],
            needs: ['nothing: no file, no lexer'],
        },
        {
            layer: 2,
            name: 'mask',
            file: LEXICAL,
            rows: lexical.masks.length,
            selector: 'masks[]',
            asserts: ['mask() output for one lexer entry', 'mask length and newline offsets are preserved'],
            needs: ['a lexer table for the language'],
        },
        {
            layer: 3,
            name: 'shapes',
            file: LEXICAL,
            rows: lexical.shapes.length,
            selector: 'shapes[]',
            asserts: ['declarations(maskedLine): kind, name, headerFrom, body, end, line'],
            needs: ['layer 2'],
        },
        {
            layer: 4,
            name: 'blocks',
            file: 'test.mjs',
            rows: null,
            selector: 'tests named scanBlocks:*',
            asserts: ['the block tree: nesting, anchors, regions, conditions, Allman / indented / arrow bodies'],
            needs: ['layers 2-3'],
        },
        {
            layer: 5,
            name: 'resolution',
            file: SECTION,
            rows: resolveRows.length,
            selector: 'rows with input !== null (they name a fixture)',
            asserts: ['text', 'startLine', 'endLine', 'ranges', 'kind', 'error', 'warning'],
            needs: ['layers 1-4'],
        },
        {
            layer: 6,
            name: 'documents',
            file: 'test.mjs',
            rows: null,
            selector: 'the document-rule tests',
            asserts: ['markers, gitignore, --lenient, region directives, the JSON/TOML/INI/YAML rules, round trips'],
            needs: ['layer 5'],
        },
        {
            layer: 7,
            name: 'differential',
            file: 'tools/compare-zig.mjs',
            rows: null,
            selector: 'two implementations, over the corpus plus generated cases',
            asserts: ['byte-for-byte agreement of two implementations'],
            needs: ['a second implementation'],
        },
    ],
    corpora: [
        {
            path: SECTION,
            rows: section.length,
            shape: 'array',
            row_fields: {
                name: 'unique; `<category>:<case>` for parse rows, a slug for resolution rows',
                mode: 'not a row field — the generator uses it to declare a case; a written row distinguishes the two kinds by `input`',
                input: 'fixture path, relative to the repository root; null for a parse row',
                reference: 'the section reference under test, without the leading `#`',
                text: 'the exact selection text, or null when the row expects an error',
                startLine: '1-based inclusive first line, or null',
                endLine: '1-based inclusive last line, or null',
                ranges: '[[from, to], ...] — the spread of text as 1-based inclusive line pairs',
                kind: 'region | declaration | property | condition | anchor | lines | multiple; null for a parse row',
                error: 'the exact thrown message, or null',
                warning: 'null, or { kind, kept, dropped } for a contradictory-modifier warning',
            },
            counts: {
                total: section.length,
                parse: parseRows.length,
                resolution: resolveRows.length,
                errors: errorRows.length,
                warnings: warnRows.length,
                by_kind: tally(resolveRows, 'kind'),
            },
            // A port that asserts fewer rows than this is skipping; the number is
            // here so a runner can assert against it instead of trusting itself.
            assert_all: true,
        },
        {
            path: LEXICAL,
            rows: lexical.masks.length + lexical.shapes.length,
            shape: 'object with masks[] and shapes[]',
            row_fields: {
                'masks[]': {
                    name: 'the lexer entry',
                    source: 'the text to mask',
                    mask: 'the exact masked text: same length, every newline at its own offset',
                },
                'shapes[]': {
                    name: 'the spelling under test',
                    path: 'a file name, to select the lexer',
                    line: 'the **raw** line handed to declarations(), not a masked one',
                    declared: 'the expected entries, field by field',
                },
            },
            counts: {
                masks: lexical.masks.length,
                shapes: lexical.shapes.length,
                total: lexical.masks.length + lexical.shapes.length,
            },
            assert_all: true,
        },
    ],
    obligations: {
        assert_every_row: 'Fail when a corpus row is unaccounted for. Skipping a row is how a port passes while being wrong.',
        read_from_repo: 'Read the corpora from the repository; do not copy them into the port, so a corpus change reaches every port at once.',
        never_hand_edit: 'The corpora are generated from the reference implementation. Regenerate, never edit.',
        hand_check_changes: 'A changed row is reviewed, not trusted: a consistently wrong implementation bakes its own bug into the contract.',
        error_rows_matter: 'The rows expecting an error are what catch an over-eager matcher.',
        discriminate: 'Every row must be one whose wrong answer looks different from its right answer.',
    },
    generators: {
        [SECTION]: 'node tools/section-vectors.mjs',
        [LEXICAL]: 'node tools/lexical-vectors.mjs',
        'src/section_vectors.zig': 'node tools/zig-vectors.mjs',
        [OUT]: 'node tools/conformance-manifest.mjs',
    },
};

const body = JSON.stringify(manifest, null, 2);
const out = `${body}\n`;

if (process.argv.includes('--check')) {
    let have = null;
    try { have = readFileSync(OUT, 'utf8'); } catch { /* absent */ }
    if (have === out) {
        console.log(`conformance manifest: ok (${section.length} section rows, ${manifest.corpora[1].rows} lexical rows)`);
        process.exit(0);
    }
    if (have === null) {
        console.error(`conformance manifest: ${OUT} is missing — run: node tools/conformance-manifest.mjs`);
    } else {
        const want = out.split('\n');
        const got = have.split('\n');
        const at = want.findIndex((line, index) => line !== got[index]);
        console.error(`conformance manifest: ${OUT} is stale — run: node tools/conformance-manifest.mjs`);
        console.error(`    first difference at line ${at + 1}`);
        console.error(`    committed: ${JSON.stringify(got[at] ?? '')}`);
        console.error(`    expected:  ${JSON.stringify(want[at] ?? '')}`);
    }
    process.exit(1);
}

writeFileSync(OUT, out, 'utf8');
console.log(`wrote ${OUT}: ${section.length} section rows (${parseRows.length} parse, ${resolveRows.length} resolution), `
    + `${lexical.masks.length} mask and ${lexical.shapes.length} shape rows`);
