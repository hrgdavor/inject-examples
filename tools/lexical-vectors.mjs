const lexerName = (path) => (path === null ? null : (lexerFor(path)?.name ?? null));

function buildMask(c) {
    const lexer = c.path === null ? null : lexerFor(c.path);
    const masked = lexer ? lexer.mask(c.source) : defaultMask(c.source);
    return { name: c.name, path: c.path, lexer: lexerName(c.path), source: c.source, masked };
}

function buildShape(c) {
    const lexer = lexerFor(c.path);
    const declared = (lexer?.declarations ? lexer.declarations(c.line) : []).map((d) => ({
        kind: d.kind,
        name: d.name,
        headerFrom: d.headerFrom,
        body: d.body ?? null,
        end: d.end ?? null,
        line: !!d.line,
    }));
    return { name: c.name, path: c.path, line: c.line, declared };
}

/**
 * Deterministic: fixed case order, fixed key order, LF endings, trailing
 * newline — and one row per line, so a diff names the row that changed.
 */
function oneRowPerLine(rows, indent) {
    const body = rows.map((row) => `${indent}  ${JSON.stringify(row)}`).join(',\n');
    return `${indent}[\n${body}\n${indent}]`;
}

function serialise() {
    const masks = oneRowPerLine(maskCases.map(buildMask), '  ');
    const shapes = oneRowPerLine(shapeCases.map(buildShape), '  ');
    return `{\n  "masks": ${masks},\n  "shapes": ${shapes}\n}\n`;
}

const out = serialise();

if (process.argv.includes('--check')) {
    let committed;
    try {
        committed = readFileSync(OUT, 'utf8');
    } catch {
        console.error('test/vectors/lexical-vectors.json is missing; run: node tools/lexical-vectors.mjs');
        process.exit(1);
    }
    if (committed === out) {
        console.log('lexical-vectors: ok');
        process.exit(0);
    }
    const want = committed.replace(/\r\n/g, '\n').split('\n');
    const have = out.replace(/\r\n/g, '\n').split('\n');
    console.error('lexical-vectors drift: the file does not match the implementation.');
    const n = Math.max(want.length, have.length);
    for (let i = 0; i < n; i++) {
        if (want[i] !== have[i]) {
            console.error(`  line ${i + 1}:`);
            console.error(`    committed: ${JSON.stringify(want[i] ?? '')}`);
            console.error(`    expected:  ${JSON.stringify(have[i] ?? '')}`);
        }
    }
    process.exit(1);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out, 'utf8');
console.log(`wrote ${maskCases.length} mask and ${shapeCases.length} shape vectors to test/vectors/lexical-vectors.json`);
