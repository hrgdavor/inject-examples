#!/usr/bin/env node
// @ts-check

/**
 * The lexical conformance corpus: what each language's **mask** and each
 * language's **declaration shapes** must answer.
 *
 * `test/vectors/section-vectors.json` pins *resolution* — which text a
 * `#<reference>` selects. It can only do that through the handful of fixtures it
 * names, so it exercises six of the eighteen lexer entries, and it says nothing
 * at all about the shape layer in isolation: a port whose `declarations()` reads
 * `publisher: String,` as the field `lisher` can still resolve every vector,
 * because no fixture contains that line.
 *
 * This corpus closes both holes. Every case is generated by running this
 * repository's own implementation:
 *
 *   - `masks`  — one row per lexer entry (plus the built-in default engine),
 *                carrying a source that exercises every construct the entry
 *                exists for, and the mask the implementation produces. The mask
 *                keeps the length and every newline offset, which is what makes
 *                `}` inside a comment or a string harmless.
 *   - `shapes` — one row per spelling a language adds to the generic `name(`
 *                heuristics, carrying the *masked* line and the declarations the
 *                implementation reports for it: kind, name, `headerFrom` (the
 *                offset the body starts at) and the body rules. These are the
 *                rows a mistranslated matcher fails, and they are deliberately
 *                chosen to discriminate — `impl<T>` against `impl`, `pub name`
 *                against `publisher`, an indented Haskell binding against a
 *                column-0 one.
 *
 *   node tools/lexical-vectors.mjs           write/update the vectors file
 *   node tools/lexical-vectors.mjs --check   compare; exit 1 and diff on drift
 *
 * `--check` is a build gate, and `test.mjs` also holds the file to a *live*
 * call, so the corpus cannot drift from the implementation it describes.
 */

