// Generate src/error_codes.zig: the failure codes as UTF-16 slices, which is the
// port's own `Str`. Derived from lib/section.mjs, so it cannot drift from the
// registry the JavaScript reports.
//
//   node tools/error-codes-zig.mjs           write the file
//   node tools/error-codes-zig.mjs --check    exit 1 when it is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { ERROR_CODES } from '../lib/section.mjs';

const OUT = 'src/error_codes.zig';

const rows = Object.entries(ERROR_CODES).sort(([, l], [, r]) => (l < r ? -1 : 1));
const literal = (text) => {
    const units = [];
    for (const ch of text) {
        const cp = ch.codePointAt(0);
        if (cp > 0xffff) {
            const high = 0xd800 + ((cp - 0x10000) >> 10);
            const low = 0xdc00 + ((cp - 0x10000) & 0x3ff);
            units.push(high, low);
        } else {
            units.push(cp);
        }
    }
    return `&[_]u16{ ${units.join(', ')} }`;
};

const body = rows.map(([name, code]) => {
    const doc = `/// \`${code}\``;
    return `${doc}\npub const ${name.toLowerCase()} = ${literal(code)};`;
}).join('\n\n');

const out = `//! The stable failure codes of RFC 1 section 3.6, as UTF-16 \`Str\` slices.
//!
//! **Generated by \`tools/error-codes-zig.mjs\` from \`lib/section.mjs\`'s
//! \`ERROR_CODES\` - do not edit.** The port reports these beside each failure's
//! message, so a host can choose a fallback by band instead of by parsing prose,
//! and \`test/vectors/section-vectors.json\` asserts the same strings.
//!
//! A code is added, never renamed: a message may be reworded without breaking a
//! caller, and only a code change is a breaking change for one that branches.

${body}
`;

if (process.argv.includes('--check')) {
    let committed = null;
    try {
        committed = readFileSync(OUT, 'utf8');
    } catch { /* absent */ }
    if (committed === out) {
        console.log(`error-codes-zig: ok (${rows.length} codes)`);
        process.exit(0);
    }
    console.error(`error-codes-zig: ${OUT} is stale — run: node tools/error-codes-zig.mjs`);
    process.exit(1);
}

writeFileSync(OUT, out, 'utf8');
console.log(`wrote ${OUT}: ${rows.length} codes`);
